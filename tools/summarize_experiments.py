"""
tools/summarize_experiments.py
------------------------------
Turns docs/evidence/experiment_results.jsonl into docs/evidence/experiment_summary.md:
one row per experiment per DAG with the facts Part F asks for.

    python tools/summarize_experiments.py
"""

import json
import os
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVIDENCE = os.path.join(ROOT, "docs", "evidence")


def seconds(tasks):
    starts = [t["start"] for t in tasks if t["start"]]
    ends = [t["end"] for t in tasks if t["end"]]
    if not starts or not ends:
        return None
    parse = lambda s: datetime.fromisoformat(s.replace("Z", "+00:00"))  # noqa: E731
    return round((max(map(parse, ends)) - min(map(parse, starts))).total_seconds())


def merge_text(r):
    if "load" in r:
        load = r.get("load") or {}
        return (f"fact: +{load.get('inserted', 0)} ins / {load.get('updated', 0)} upd / "
                f"{load.get('changed', 0)} changed / {load.get('unchanged_or_older', 0)} kept-newer") if load else "—"
    parts = []
    for m in (r.get("merge_orders") or []) + (r.get("merge_increments") or []):
        parts.append(f"{m['source_file']}: +{m['inserted']} ins / {m['updated']} upd / {m['changed']} changed / "
                     f"{m['skipped']} kept-newer")
    return "; ".join(parts) or "—"


def main():
    with open(os.path.join(EVIDENCE, "experiment_results.jsonl"), encoding="utf-8") as f:
        rows = [json.loads(line) for line in f]
    out = ["<!-- generated by tools/summarize_experiments.py -->",
           "| Experiment | DAG | Run state | Wall time | Not-green tasks (state, tries) | Rows extracted / loaded / "
           "quarantined | Load / MERGE | DQ checks raising |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        dag = "ETL" if "etl" in r["dag_id"] else "ELT"
        bad = [f"{t['task_id']} ({t['state']}, {t['try_number']})" for t in r["tasks"] if t["state"] != "success"]
        retried = [f"{t['task_id']} (success after {t['try_number']} tries)" for t in r["tasks"]
                   if t["state"] == "success" and (t["try_number"] or 1) > 1]
        pr = (r["warehouse"]["pipeline_run"] or [{}])[0]
        dq = r["warehouse"]["dq_flagged"]
        fails = sum(1 for d in dq if d["status"] == "FAIL")
        warns = sum(1 for d in dq if d["status"] == "WARN")
        notes = [d["check_name"] for d in dq if d["check_name"].startswith(
            ("orders_volume", "orders_store_price", "orders_fresh_vs_batch", "orders_schema", "payments_order_fk"))]
        out.append(
            f"| {r['experiment']} | {dag} | {r['state']} | {seconds(r['tasks'])} s | "
            f"{'; '.join(bad[:3] + retried) + (' …' if len(bad) > 3 else '') or '—'} | "
            f"{pr.get('rows_extracted')} / {pr.get('rows_loaded')} / {pr.get('rows_quarantined')} | {merge_text(r)} | "
            f"{fails} FAIL, {warns} WARN{(' (' + ', '.join(notes) + ')') if notes else ''} |")
    target = os.path.join(EVIDENCE, "experiment_summary.md")
    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
