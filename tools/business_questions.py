"""
tools/business_questions.py
---------------------------
Runs every query in include/sql/business_questions.sql (plus optional extra .sql
files) against include/warehouse_athresh.duckdb and writes the SQL and results as
markdown to docs/evidence/<name>.md.

    python tools/business_questions.py                                   # business questions
    python tools/business_questions.py include/sql/evidence_queries.sql  # audit / governance evidence
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import duckdb  # noqa: E402

from include.nammamart.config import SQL_DIR, WAREHOUSE_DB  # noqa: E402


MONEY_LIKE = ("revenue", "amount", "margin", "price", "pct", "minutes", "seconds", "spend", "cost", "difference")


def blocks(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    for m in re.finditer(r"^-- name: (\S+) \| (.+?)\n(.*?)(?=\n-- name: |\Z)", text, re.S | re.M):
        yield m.group(1), m.group(2).strip(), m.group(3).strip()


def main(path=os.path.join(SQL_DIR, "business_questions.sql")):
    con = duckdb.connect(WAREHOUSE_DB, read_only=True)
    out = [f"<!-- generated by tools/business_questions.py from {os.path.relpath(path, ROOT)} -->\n"]
    for _, title, sql in blocks(path):
        df = con.execute(sql).df()
        for col in df.columns:
            if str(df[col].dtype).startswith("datetime64") and (df[col].dropna().dt.normalize() == df[col].dropna()).all():
                df[col] = df[col].dt.date  # DATE columns: drop the 00:00:00
            elif (df[col].dtype == "float64" and not any(k in col for k in MONEY_LIKE)
                  and (df[col].dropna() % 1 == 0).all()):
                df[col] = df[col].astype("Int64")  # counts: sum() of BIGINT arrives as float
        table = df.to_markdown(index=False, floatfmt=",.2f", intfmt=",") if len(df) else "_(no rows)_"
        out.append(f"#### {title}\n\n```sql\n{sql}\n```\n\n{table}\n")
    con.close()
    target = os.path.join(ROOT, "docs", "evidence", os.path.basename(path).replace(".sql", ".md"))
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote {target}")


if __name__ == "__main__":
    main(*sys.argv[1:])
